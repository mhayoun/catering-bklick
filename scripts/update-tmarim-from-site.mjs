// One-off script: enriches the "קייטרינג תמרים" caterer record (added by scripts/add-tmarim.mjs
// from its cateringisrael.co.il directory listing) with data from the business's own website,
// https://protamar.com/ - which has 13 dedicated, fully itemized menu pages (much like
// aleshelzait.co.il), a real address, and a scanned kashrut certificate.
//
// Corrections vs. the original directory-sourced record:
// - cateringTypes was ['dairy'] only (directory listing under-reported it) - the site has full
//   meat menus (חתונה בשרית, אסאדו, ברביקיו, שבת חתן) - now ['dairy', 'meat'].
// - kashrutLevels was guessed as ['mehadrin', 'glatt'] from the directory's generic checkboxes.
//   The site links an actual scanned kashrut certificate (בד"ץ חוג חתם סופר, פתח תקוה) which
//   states the business is "כשרה חלבי למהדרין מן המהדרין" - dairy-only, mehadrin, but NOT glatt
//   (glatt is a meat-kashrut term and doesn't apply to a dairy certificate) - corrected to
//   ['mehadrin']. No matching KASHRUT_LEVELS entry exists for "Chatam Sofer" specifically, and
//   the certificate says nothing about meat kashrut, so nothing further is added.
// - address/website were blank - now filled in (address confirmed against the certificate scan).
// - eventTypes gains henna/shabbat_chatan, confirmed by the site's own nav pages
//   (קייטרינג-לחינה, קייטרינג-לשבת-חתן) and by the שבת חתן menu's actual content.
//
// logo: the site's only logo asset (1.5-1-1.svg) is solid-white, meant for the dark maroon
// navbar background - rendered on our light card backgrounds it's invisible, so it is
// deliberately NOT used here (confirmed by rendering it against white in the scratchpad).
//
// packages: each of the 13 menu pages becomes one formula package. None publish a price-per-
// guest or minimum guest count, so pricePerGuest reuses the directory's priceFrom (300) as an
// estimate and minGuests is a judgment call - both should be adjusted via the dashboard edit
// form once real figures are known (same caveat as scripts/add-aleshelzait.mjs). Where a menu
// page states an explicit "X לבחירה" (X to choose) count per section, that's reflected in
// categoryLimits; the app's schema has one limit per MENU_CATEGORIES bucket, so where a source
// page splits one bucket into multiple sub-sections with different limits (e.g. wedding-dairy's
// "עיקריות" limit 4 + "דגים" limit 1, both folded into main_courses), the limit is approximated
// rather than exactly reproduced - noted per package below.
//
// Usage: node --env-file=.env.local scripts/update-tmarim-from-site.mjs

import { kv } from '@vercel/kv';
